// Writes supabase/migrations/0002_seed_rinks.sql from data/rinks.json, so the database and the local store start from the
// same rinks. Run: node tools/seed-sql.mjs
import { readFileSync, writeFileSync } from "node:fs";

const seed = JSON.parse(readFileSync(new URL("../data/rinks.json", import.meta.url), "utf8"));
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const orgs = [...new Set(seed.rinks.map((r) => r.org_id).filter(Boolean))];
const orgNames = { snoking: "Sno-King Ice Arenas", "rectimes-lic": "Lynnwood Ice Center and Olympicview Arena" };
const lines = [
  "-- The rinks from the rink survey (ROADMAP.md, 2026-11-15). Generated by tools/seed-sql.mjs from data/rinks.json; do not edit by hand.",
  ...orgs.map((o) => `insert into public.orgs (id, name) values (${q(o)}, ${q(orgNames[o] || o)});`),
  ...seed.rinks.map((r) => `insert into public.rinks (id, org_id, name, city, address, website, schedule_page, time_zone, color, note) values (${[r.id, r.org_id, r.name, r.city, r.address, r.website, r.schedule_page, r.time_zone, r.color, r.note || null].map(q).join(", ")});`),
  ...seed.sources.map((s) => `insert into public.schedule_sources (id, rink_id, kind, via, calendar_id, url, label, approved, terms_checked, terms_note) values (${[s.id, s.rinkId, s.kind, s.via || "ics", s.calendarId || null, s.url, s.label].map(q).join(", ")}, ${s.approved ? "true" : "false"}, ${q(s.termsChecked)}, ${q(s.termsNote)});`),
];
writeFileSync(new URL("../supabase/migrations/0002_seed_rinks.sql", import.meta.url), lines.join("\n") + "\n");
console.log(`wrote ${seed.rinks.length} rinks and ${seed.sources.length} sources`);
